export function DocumentationCenter() {
  const [query, setQuery] = useState("");
  const normalizedQuery = query.trim().toLocaleLowerCase("ru");
  const visibleGuides = useMemo(() => guides.filter((guide) => !normalizedQuery || `${guide.title} ${guide.summary} ${guide.search} ${guide.steps.join(" ")} ${guide.notes?.join(" ") ?? ""}`.toLocaleLowerCase("ru").includes(normalizedQuery)), [normalizedQuery]);

  return (
    <div className={styles.page}>
      <header className={styles.topbar}>
        <h1>Документация</h1>
        <label className={styles.search}>
          <span aria-hidden="true">⌕</span>
          <input type="search" value={query} onChange={(event) => setQuery(event.target.value)} placeholder="Найти инструкцию" />
        </label>
      </header>

      <main className={styles.content}>
        <section className={styles.intro}>
          <div>
            <span className={styles.eyebrow}>Центр помощи</span>
            <h2>Как работать в Estate CRM</h2>
            <p>Короткие инструкции по основным разделам, подключениям и доступам. Статус рядом с каждой темой показывает, что уже можно использовать, а что ещё развивается.</p>
          </div>
          <aside>
            <strong>Рекомендуемый маршрут</strong>
            <span>Лид → контакт и сделка → ответственный → задача → результат</span>
          </aside>
        </section>

        <section className={styles.legend} aria-label="Статусы функций">
          <span><i className={styles.ready} /> Работает</span>
          <span><i className={styles.partial} /> Частично</span>
          <span><i className={styles.planned} /> В разработке</span>
          <small>Обновлено 9 сентября 2026</small>
        </section>

        <div className={styles.layout}>
          <nav className={styles.contents} aria-label="Содержание документации">
            <span>Содержание</span>
            {guides.map((guide) => <a key={guide.id} href={`#${guide.id}`}><b>{guide.number}</b>{guide.title}</a>)}
            <a href="#roadmap"><b>11</b>Что ещё появится</a>
          </nav>

          <div className={styles.guides}>
            {visibleGuides.length === 0 ? (
              <div className={styles.empty}>
                <strong>Ничего не найдено</strong>
                <p>Попробуйте другой запрос — например, «Telegram», «приглашение» или «сделка».</p>
                <button type="button" onClick={() => setQuery("")}>Сбросить поиск</button>
              </div>
            ) : visibleGuides.map((guide) => (
              <article className={styles.guide} id={guide.id} key={guide.id}>
                <header>
                  <span className={styles.guideNumber}>{guide.number}</span>
                  <div><h3>{guide.title}</h3><p>{guide.summary}</p></div>
                  <span className={`${styles.status} ${styles[guide.status]}`}>{guide.statusLabel}</span>
                </header>
                <ol>{guide.steps.map((step) => <li key={step}>{step}</li>)}</ol>
                {guide.notes && <div className={styles.notes}>{guide.notes.map((note) => <p key={note}><span>Важно</span>{note}</p>)}</div>}
                {guide.href && <Link className={styles.openLink} href={guide.href}>Открыть раздел <span>→</span></Link>}
              </article>
            ))}

            {!normalizedQuery && <section className={styles.roadmap} id="roadmap">
              <header><span className={styles.guideNumber}>11</span><div><h3>Что ещё появится</h3><p>Функции, которые запланированы, но пока не должны восприниматься как готовые.</p></div><span className={`${styles.status} ${styles.planned}`}>В разработке</span></header>
              <div className={styles.roadmapGrid}>{roadmap.map(([title, description]) => <div key={title}><strong>{title}</strong><p>{description}</p></div>)}</div>
            </section>}
          </div>
        </div>
      </main>
    </div>
  );
}
